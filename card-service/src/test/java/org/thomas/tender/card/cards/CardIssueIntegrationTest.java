package org.thomas.tender.card.cards;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.testcontainers.service.connection.ServiceConnection;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.http.MediaType;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;
import org.testcontainers.postgresql.PostgreSQLContainer;

import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.hamcrest.Matchers.containsString;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.header;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

// Full app context + real Postgres. No Mockito: controller, service and repository are all real.
// MockMvc only skips the network hop (no Tomcat, no port).
@SpringBootTest
@AutoConfigureMockMvc
@Testcontainers
class CardIssueIntegrationTest {

    @Container
    @ServiceConnection
    static PostgreSQLContainer postgreSQLContainer = new PostgreSQLContainer("postgres:18");

    private final MockMvc mockMvc;               // sends the request in
    private final CardRepository cardRepository; // checks what landed in the DB

    @Autowired
        // JUnit creates the test class, so Spring needs this to inject the constructor
    CardIssueIntegrationTest(MockMvc mockMvc, CardRepository cardRepository) {
        this.mockMvc = mockMvc;
        this.cardRepository = cardRepository;
    }

    @Test
    void postCards_ValidRequest_PersistsCardAndReturns201() throws Exception {
        // Arrange: only the client's input. id and createdAt are generated by the server.
        String body = """
                {"initialBalance": 25.00, "currency": "USD"}
                """;

        // Act + assert the HTTP response
        MvcResult result = mockMvc.perform(post("/cards")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(body))
                .andExpect(status().isCreated())
                .andExpect(header().string("Location", containsString("/cards/")))
                .andExpect(jsonPath("$.id").isNotEmpty())        // generated by Hibernate
                .andExpect(jsonPath("$.createdAt").isNotEmpty()) // @CreationTimestamp, needs the flush
                .andExpect(jsonPath("$.balance").value(25.00))
                .andExpect(jsonPath("$.currency").value("USD"))
                .andReturn(); // hands back the response so we can read the generated id

        // We can't know the id in advance, so read it from the Location header (.../cards/{id})
        String location = result.getResponse().getHeader("Location");
        UUID id = UUID.fromString(location.substring(location.lastIndexOf('/') + 1));

        // Assert the DB: the POST's transaction already committed, and findById runs in a
        // new one with an empty persistence context, so this is a real SELECT (no clear() needed).
        Card found = cardRepository.findById(id).orElseThrow();
        assertThat(found.getBalance()).isEqualByComparingTo("25.00");
        assertThat(found.getCurrency()).isEqualTo("USD");
        assertThat(found.getCreatedAt()).isNotNull();
    }
}
